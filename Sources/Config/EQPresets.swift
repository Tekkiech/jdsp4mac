    /// The preset these gains match within 0.01 dB (as JDSP4Linux's reverseLookup), or nil.
    public static func name(matching gains: [Double]) -> String? {
        all.first { p in p.gains.count == gains.count && zip(p.gains, gains).allSatisfy { abs($0 - $1) <= 0.01 } }?.name
    }

    public static func gains(named name: String) -> [Double]? {
        all.first { $0.name == name }?.gains
